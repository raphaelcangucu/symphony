defmodule SymphonyElixir.CoreTest do
  use SymphonyElixir.TestSupport

  @prompt_project_default "You are an agent for this repository."

  # Seeds a DB-owned project carrying the given prompt template (and optional
  # workflow_config, e.g. hooks). Global-less orchestration resolves prompts
  # only from a project's setup, so prompt-builder/agent-runner tests bind their
  # issue to this project via `project_slug`. Cleans the tracker before and
  # after so projects never leak across the shared CoreTest database.
  defp seed_prompt_project!(prompt, workflow_config \\ %{}) do
    {:ok, _repo, _apps} =
      Ecto.Migrator.with_repo(SymphonyElixir.Repo, fn repo ->
        Ecto.Migrator.run(repo, :up, all: true)
      end)

    SymphonyElixir.TestSupport.truncate_tracker!(SymphonyElixir.Repo)
    on_exit(fn -> SymphonyElixir.TestSupport.truncate_tracker!(SymphonyElixir.Repo) end)

    slug = "core-prompt-#{System.unique_integer([:positive])}"

    {:ok, project} =
      SymphonyElixir.LocalTracker.Context.ensure_project(%{name: slug, slug: slug, tracker_kind: "local"})

    {:ok, _setup} =
      %SymphonyElixir.LocalTracker.ProjectSetup{}
      |> SymphonyElixir.LocalTracker.ProjectSetup.changeset(%{
        project_id: project.id,
        workflow_markdown: SymphonyElixir.Workflow.to_markdown(workflow_config, prompt || ""),
        validation_commands: %{"commands" => []},
        scan_summary: %{}
      })
      |> SymphonyElixir.Repo.insert()

    slug
  end

  defp empty_dispatch_state do
    %Orchestrator.State{
      max_concurrent_agents: 3,
      running: %{},
      claimed: MapSet.new(),
      agent_totals: %{input_tokens: 0, output_tokens: 0, total_tokens: 0, seconds_running: 0},
      retry_attempts: %{}
    }
  end

  test "dispatch eligibility resolves states from the issue's own project, not global defaults" do
    slug =
      seed_prompt_project!("Prompt", %{
        "tracker" => %{
          "active_states" => ["Doing"],
          "terminal_states" => ["Shipped"]
        }
      })

    state = empty_dispatch_state()

    custom_active_issue = %Issue{
      id: "per-project-doing",
      identifier: "PP-1",
      project_slug: slug,
      title: "Custom active state",
      state: "Doing",
      labels: []
    }

    global_active_issue = %{custom_active_issue | id: "per-project-todo", identifier: "PP-2", state: "Todo"}

    # "Doing" is not a global active state, but it is for this project.
    assert Orchestrator.should_dispatch_issue_for_test(custom_active_issue, state)

    # "Todo" is the global default active state, but this project does not use it.
    refute Orchestrator.should_dispatch_issue_for_test(global_active_issue, state)
  end

  test "require_symphony_label gate blocks unlabeled issues and the toggle disables it" do
    slug = seed_prompt_project!("Prompt", %{"tracker" => %{"active_states" => ["Todo"]}})

    SymphonyElixir.Repo.delete_all(SymphonyElixir.Settings.Setting)
    on_exit(fn -> SymphonyElixir.Repo.delete_all(SymphonyElixir.Settings.Setting) end)

    state = empty_dispatch_state()

    labeled_issue = %Issue{
      id: "labeled",
      identifier: "PP-10",
      project_slug: slug,
      title: "Labeled issue",
      state: "Todo",
      labels: ["symphony:codex"],
      assigned_to_worker: true
    }

    unlabeled_issue = %{
      labeled_issue
      | id: "unlabeled",
        identifier: "PP-11",
        labels: [],
        assigned_to_worker: false
    }

    # Default (require_symphony_label = true): only the routable issue dispatches.
    assert Orchestrator.should_dispatch_issue_for_test(labeled_issue, state)
    refute Orchestrator.should_dispatch_issue_for_test(unlabeled_issue, state)

    # Toggle off: the label gate is bypassed and the unlabeled issue is eligible.
    {:ok, _} = SymphonyElixir.Settings.put("orchestrator", "require_symphony_label", false)
    assert Orchestrator.should_dispatch_issue_for_test(unlabeled_issue, state)
  end

  test "operator-paused issues are gated out of autonomous dispatch until resumed" do
    slug = seed_prompt_project!("Prompt", %{"tracker" => %{"active_states" => ["Todo"]}})

    issue = %Issue{
      id: "paused-issue-1",
      identifier: "PP-20",
      project_slug: slug,
      title: "Paused issue",
      state: "Todo",
      labels: ["symphony:codex"],
      assigned_to_worker: true
    }

    # Eligible for autonomous dispatch while not paused.
    assert Orchestrator.should_dispatch_issue_for_test(issue, empty_dispatch_state())

    # A deliberate operator pause must stop the poll loop from re-dispatching it.
    paused_state = %{empty_dispatch_state() | paused: MapSet.new([issue.id])}
    refute Orchestrator.should_dispatch_issue_for_test(issue, paused_state)
  end

